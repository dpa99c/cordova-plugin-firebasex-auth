/**
 * @fileoverview Firebase Authentication plugin interface for Cordova.
 * Provides methods for user authentication via email/password, phone number, OAuth providers
 * (Google, Apple, Microsoft, Facebook), custom tokens, anonymous sign-in, multi-factor
 * authentication (MFA), credential management, and user profile operations.
 * @module firebasex-auth
 */
var exec = require('cordova/exec');

/**
 * @private
 * @constant {string} SERVICE - The native plugin service name used for Cordova exec calls.
 */
var SERVICE = 'FirebasexAuthPlugin';

/**
 * @private
 * Wraps a callback function to ensure its argument is coerced to a boolean.
 * @param {function} callback - The callback to wrap.
 * @returns {function} A wrapper function that calls the original callback with a boolean value.
 */
var ensureBooleanFn = function (callback) {
    return function (result) {
        callback(ensureBoolean(result));
    }
};

/**
 * @private
 * Coerces a value to a boolean, handling string representations "true"/"false".
 * @param {*} value - The value to coerce.
 * @returns {boolean} The boolean result.
 */
var ensureBoolean = function (value) {
    if (value === "true") {
        value = true;
    } else if (value === "false") {
        value = false;
    }
    return !!value;
};

/**
 * @private
 * Wraps an error callback to extract structured auth error information.
 * If the error result is an object (e.g. from an MFA challenge), it extracts
 * the `errorMessage` and `secondFactors` array; otherwise passes the raw error string.
 * @param {function} errorCallback - The error callback to wrap. Called with (errorMessage, secondFactors).
 * @returns {function} A wrapper function that parses the native error result.
 */
var handleAuthErrorResult = function (errorCallback) {
    return function (result) {
        var errorMessage, secondFactors;
        if (typeof result === 'object') {
            errorMessage = result.errorMessage;
            secondFactors = result.secondFactors;
        } else {
            errorMessage = result;
        }
        errorCallback(errorMessage, secondFactors);
    }
};

/**
 * @private
 * Stored callback for auth state changes, invoked by native code via `_onAuthStateChange`.
 * @type {function}
 */
var onAuthStateChangeCallback = function () { };

/**
 * @private
 * Stored callback for ID token changes, invoked by native code via `_onAuthIdTokenChange`.
 * @type {function}
 */
var onAuthIdTokenChangeCallback = function () { };

/***********************
 * Protected internals
 ***********************/

/**
 * @private
 * Called by native code when the Firebase Auth state changes (user signs in or out).
 * Forwards the event to the registered `onAuthStateChangeCallback`.
 * @param {boolean} userSignedIn - Whether a user is currently signed in.
 */
exports._onAuthStateChange = function (userSignedIn) {
    onAuthStateChangeCallback(userSignedIn);
};

/**
 * @private
 * Called by native code when the Firebase Auth ID token changes.
 * Forwards the event to the registered `onAuthIdTokenChangeCallback`.
 * @param {boolean} token - Whether a user is currently signed in (true if ID token exists).
 */
exports._onAuthIdTokenChange = function (token) {
    onAuthIdTokenChangeCallback(token);
};

// Phone / MFA

/**
 * Starts phone number verification for phone-based authentication.
 * On Android, may result in instant verification without requiring an SMS code.
 * @param {function} success - Called with a credential object containing:
 *   - `verificationId` {string} - The verification session ID (if SMS sent).
 *   - `instantVerification` {boolean} - Whether verification completed instantly.
 *   - `id` {string} - Native credential ID (if instant verification).
 * @param {function} error - Called with an error message string on failure.
 * @param {string} phoneNumber - The phone number to verify, in E.164 format (e.g. "+1234567890").
 * @param {object} [opts={}] - Optional parameters:
 *   - `timeOutDuration` {number} - Timeout in seconds for auto-retrieval (Android only, default 30).
 *   - `fakeVerificationCode` {string} - A fake verification code for testing (Android only).
 *   - `requireSmsValidation` {boolean} - If true, forces SMS verification even if instant verification is available (Android only).
 */
exports.verifyPhoneNumber = function (success, error, phoneNumber, opts) {
    if (typeof opts !== 'object') opts = {};
    exec(function (credential) {
        if (typeof credential === 'object') {
            credential.instantVerification = ensureBoolean(credential.instantVerification);
        }
        success(credential);
    }, error, SERVICE, "verifyPhoneNumber", [phoneNumber, opts]);
};

/**
 * Enrolls a phone number as a second authentication factor (MFA) for the current user.
 * If no `displayName` is provided in opts, one is auto-generated by masking all but the last 4 digits.
 * @param {function} success - Called with the enrollment result (contains `verificationId` for SMS code entry).
 * @param {function} error - Called with an error message string on failure.
 * @param {string} number - The phone number to enroll as a second factor, in E.164 format.
 * @param {object} [opts={}] - Optional parameters:
 *   - `displayName` {string} - A display name for this factor. Auto-generated if not provided.
 */
exports.enrollSecondAuthFactor = function (success, error, number, opts) {
    if (typeof opts !== 'object') opts = {};
    if (!opts.displayName) {
        var s_number = number + '',
            last4Digits = s_number.slice(-4),
            firstDigits = s_number.slice(0, -4);
        opts.displayName = firstDigits.replace(/[0-9]/g, '*') + last4Digits;
    }
    exec(success, error, SERVICE, "enrollSecondAuthFactor", [number, opts]);
};

/**
 * Verifies a second authentication factor during an MFA sign-in challenge or enrollment.
 * @param {function} success - Called on successful MFA verification.
 * @param {function} error - Called with an error message string on failure.
 * @param {object} params - Verification parameters:
 *   - `selectedIndex` {number} - Index of the enrolled factor to verify (for MFA challenge).
 *   - `verificationId` {string} - The verification ID from phone verification.
 *   - `code` {string} - The SMS verification code entered by the user.
 * @param {object} [opts={}] - Additional options (reserved for future use).
 */
exports.verifySecondAuthFactor = function (success, error, params, opts) {
    if (typeof params !== 'object') return error("'params' object must be specified");
    if (typeof opts !== 'object') opts = {};
    exec(success, error, SERVICE, "verifySecondAuthFactor", [params, opts]);
};

